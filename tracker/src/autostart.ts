// Registers the tracker with Windows Task Scheduler so it starts, hidden, at login.
//
// Node always opens a console window, so the task runs wscript.exe with a tiny
// generated launcher that starts the supervisor with its window hidden, and
// waits for it. While it waits the task counts as running; if the supervisor
// ever dies, the task's 5-minute repetition starts it again.
import { execFileSync } from 'node:child_process';
import { existsSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { type AppIdentity, setShortcutAppId } from './appIdentity.ts';
import { APP_ID } from './notify.ts';

export const DEFAULT_TASK_NAME = 'Raqib';
/** What the task was called before the tracker became رقيب. Replaced on install. */
export const LEGACY_TASK_NAME = 'Personal Activity Tracker';
const SHORTCUT_NAME = 'رقيب.lnk';
const ICON_FILE = fileURLToPath(new URL('../ui/icon.ico', import.meta.url));

/** Environment variables passed on to the hidden tracker, when set at install time. */
const PASSED_ON = ['ACTIVITY_TRACKER_HOME', 'ACTIVITY_TRACKER_CONFIG', 'ACTIVITY_TRACKER_CATEGORIES', 'CLAUDE_CONFIG_DIR'];

export function taskName(env: NodeJS.ProcessEnv = process.env): string {
  return env['ACTIVITY_TRACKER_TASK'] ?? DEFAULT_TASK_NAME;
}

const vbsString = (text: string) => `"${text.replaceAll('"', '""')}"`;
const xmlText = (text: string) =>
  text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');

/** A VBScript that starts `node main.js supervise` with no window, and waits for it. */
export function launcherScript(nodePath: string, mainScript: string, env: NodeJS.ProcessEnv = process.env): string {
  const lines = [
    "' Generated by 'raqib install'. Starts رقيب with no window.",
    'Set shell = CreateObject("WScript.Shell")',
  ];
  for (const name of PASSED_ON) {
    const value = env[name];
    if (value) lines.push(`shell.Environment("Process")(${vbsString(name)}) = ${vbsString(value)}`);
  }
  const command = `${vbsString(`"${nodePath}" "${mainScript}" supervise`)}`;
  lines.push(`WScript.Quit shell.Run(${command}, 0, True)`);
  return `${lines.join('\r\n')}\r\n`;
}

/** Task Scheduler XML: at login, for this user only, never time-limited, never stopped on battery. */
export function taskXml(user: string, launcher: string): string {
  return `<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo>
    <Description>رقيب (Raqib), your activity tracker. Records which app is in front, locally only.</Description>
  </RegistrationInfo>
  <Triggers>
    <LogonTrigger>
      <Enabled>true</Enabled>
      <UserId>${xmlText(user)}</UserId>
      <Repetition>
        <Interval>PT5M</Interval>
        <StopAtDurationEnd>false</StopAtDurationEnd>
      </Repetition>
    </LogonTrigger>
  </Triggers>
  <Principals>
    <Principal id="Author">
      <UserId>${xmlText(user)}</UserId>
      <LogonType>InteractiveToken</LogonType>
      <RunLevel>LeastPrivilege</RunLevel>
    </Principal>
  </Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <AllowHardTerminate>true</AllowHardTerminate>
    <StartWhenAvailable>true</StartWhenAvailable>
    <RunOnlyIfNetworkAvailable>false</RunOnlyIfNetworkAvailable>
    <IdleSettings>
      <StopOnIdleEnd>false</StopOnIdleEnd>
      <RestartOnIdle>false</RestartOnIdle>
    </IdleSettings>
    <AllowStartOnDemand>true</AllowStartOnDemand>
    <Enabled>true</Enabled>
    <Hidden>false</Hidden>
    <RunOnlyIfIdle>false</RunOnlyIfIdle>
    <WakeToRun>false</WakeToRun>
    <ExecutionTimeLimit>PT0S</ExecutionTimeLimit>
    <Priority>7</Priority>
    <RestartOnFailure>
      <Interval>PT1M</Interval>
      <Count>999</Count>
    </RestartOnFailure>
  </Settings>
  <Actions Context="Author">
    <Exec>
      <Command>wscript.exe</Command>
      <Arguments>//B //NoLogo "${xmlText(launcher)}"</Arguments>
    </Exec>
  </Actions>
</Task>
`;
}

function schtasks(args: string[]): { ok: boolean; output: string } {
  try {
    return { ok: true, output: execFileSync('schtasks.exe', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }) };
  } catch (error) {
    const e = error as { stdout?: string; stderr?: string };
    return { ok: false, output: `${e.stdout ?? ''}${e.stderr ?? ''}`.trim() };
  }
}

export function currentUser(env: NodeJS.ProcessEnv = process.env): string {
  return env['USERDOMAIN'] ? `${env['USERDOMAIN']}\\${env['USERNAME']}` : (env['USERNAME'] ?? '');
}

/** A VBScript that opens رقيب's window without flashing a console. Run by the Start menu shortcut. */
export function openerScript(nodePath: string, mainScript: string): string {
  return [
    "' Generated by 'raqib install'. Opens رقيب's window.",
    'Set shell = CreateObject("WScript.Shell")',
    `shell.Run ${vbsString(`"${nodePath}" "${mainScript}" open`)}, 0, False`,
    '',
  ].join('\r\n');
}

export function startMenuShortcut(env: NodeJS.ProcessEnv = process.env): string | null {
  const appData = env['APPDATA'];
  return appData ? join(appData, 'Microsoft', 'Windows', 'Start Menu', 'Programs', SHORTCUT_NAME) : null;
}

const psString = (text: string) => `'${text.replaceAll("'", "''")}'`;

function powershell(script: string): string {
  return execFileSync('powershell.exe', ['-NoProfile', '-NonInteractive', '-EncodedCommand', Buffer.from(script, 'utf16le').toString('base64')], {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'ignore'],
    windowsHide: true,
  });
}

/** Where the desktop shortcut goes. Asks Windows, since OneDrive often moves the Desktop folder. */
export function desktopShortcut(): string | null {
  try {
    const folder = powershell("[Console]::OutputEncoding = [Text.Encoding]::UTF8; [Environment]::GetFolderPath('Desktop')").trim();
    return folder ? join(folder, SHORTCUT_NAME) : null;
  } catch {
    return null;
  }
}

/** Writes the script that opens رقيب's window without a console, and returns its path. */
function writeOpener(dataFolder: string, mainScript: string): string {
  const opener = join(dataFolder, 'open-window.vbs');
  // UTF-16 with a BOM, so the Arabic in the comment survives.
  writeFileSync(opener, Buffer.concat([Buffer.from([0xff, 0xfe]), Buffer.from(openerScript(process.execPath, mainScript), 'utf16le')]));
  return opener;
}

const openerArguments = (opener: string) => `//B //NoLogo "${opener}"`;

/** What the taskbar needs to show رقيب's window as رقيب, not as the browser. */
export function appIdentity(dataFolder: string, mainScript: string): AppIdentity {
  const opener = writeOpener(dataFolder, mainScript);
  return {
    id: APP_ID,
    name: 'رقيب',
    relaunch: `wscript.exe ${openerArguments(opener)}`,
    icon: `${ICON_FILE},0`,
  };
}

/** Creates (or refreshes) a shortcut at `shortcut` that opens رقيب's window. Per user, no admin. */
function writeShortcut(dataFolder: string, mainScript: string, shortcut: string): void {
  const opener = writeOpener(dataFolder, mainScript);
  const script = [
    '$shell = New-Object -ComObject WScript.Shell',
    `$link = $shell.CreateShortcut(${psString(shortcut)})`,
    "$link.TargetPath = 'wscript.exe'",
    `$link.Arguments = ${psString(openerArguments(opener))}`,
    "$link.Description = 'رقيب: your day, tasks, and reminders'",
    ...(existsSync(ICON_FILE) ? [`$link.IconLocation = ${psString(ICON_FILE)}`] : []),
    '$link.Save()',
  ].join('; ');
  powershell(script);
  // Same ID as the window, so the pinned shortcut and the open window share one taskbar button.
  setShortcutAppId(shortcut, APP_ID);
}

/** Adds "رقيب" to the Start menu, so its window is one click away. */
function installShortcut(dataFolder: string, mainScript: string): void {
  const shortcut = startMenuShortcut();
  if (shortcut) writeShortcut(dataFolder, mainScript, shortcut);
}

/** Adds (or refreshes) "رقيب" on the desktop. Run after every build. Returns where it went. */
export function installDesktopShortcut(dataFolder: string, mainScript: string): string | null {
  // Keep the Start menu one (made by "raqib install") pointing at this build too.
  const startMenu = startMenuShortcut();
  if (startMenu && existsSync(startMenu)) writeShortcut(dataFolder, mainScript, startMenu);
  const shortcut = desktopShortcut();
  if (shortcut) writeShortcut(dataFolder, mainScript, shortcut);
  return shortcut;
}

/** Writes the launcher and registers (or replaces) the task. */
export function install(dataFolder: string, mainScript: string, name: string = taskName()): void {
  const launcher = join(dataFolder, 'launch-hidden.vbs');
  writeFileSync(launcher, launcherScript(process.execPath, mainScript));
  const xmlFile = join(dataFolder, 'autostart-task.xml');
  // Task Scheduler expects UTF-16 with a byte-order mark.
  writeFileSync(xmlFile, Buffer.concat([Buffer.from([0xff, 0xfe]), Buffer.from(taskXml(currentUser(), launcher), 'utf16le')]));
  const result = schtasks(['/Create', '/TN', name, '/XML', xmlFile, '/F']);
  if (!result.ok) throw new Error(`Task Scheduler refused the task: ${result.output}`);
  // The old task would start a second supervisor at the next login.
  if (name === DEFAULT_TASK_NAME && isInstalled(LEGACY_TASK_NAME)) schtasks(['/Delete', '/TN', LEGACY_TASK_NAME, '/F']);
  try {
    installShortcut(dataFolder, mainScript);
  } catch {
    // The shortcut is a convenience; "raqib open" works without it.
  }
}

/** True if the task existed and was removed. */
export function uninstall(name: string = taskName()): boolean {
  const shortcut = startMenuShortcut();
  if (shortcut) rmSync(shortcut, { force: true });
  const desktop = desktopShortcut();
  if (desktop) rmSync(desktop, { force: true });
  if (name === DEFAULT_TASK_NAME && isInstalled(LEGACY_TASK_NAME)) schtasks(['/Delete', '/TN', LEGACY_TASK_NAME, '/F']);
  if (!isInstalled(name)) return false;
  const result = schtasks(['/Delete', '/TN', name, '/F']);
  if (!result.ok) throw new Error(`Task Scheduler could not remove the task: ${result.output}`);
  return true;
}

export function isInstalled(name: string = taskName()): boolean {
  return schtasks(['/Query', '/TN', name]).ok;
}

/** True if only the task from before the rename is there: "raqib install" will replace it. */
export function onlyLegacyInstalled(name: string = taskName()): boolean {
  return name === DEFAULT_TASK_NAME && !isInstalled(name) && isInstalled(LEGACY_TASK_NAME);
}

/** Runs the task now, as if you had just logged in. */
export function runNow(name: string = taskName()): void {
  const result = schtasks(['/Run', '/TN', name]);
  if (!result.ok) throw new Error(`Task Scheduler could not start the task: ${result.output}`);
}
